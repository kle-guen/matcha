/**
 * The user data transfer object.
 */
export class UserDto {

	/**
	 * The name of the user.
	 */
	name!: string;

	/**
	 * The first name of the user.
	 */
	firstName!: string;

	/**
	 * The username of the user.
	 */
	username!: string;

	/**
	 * The email of the user.
	 */
	email!: string;

	/**
	 * The password of the user.
	 */
	password!: string;

}